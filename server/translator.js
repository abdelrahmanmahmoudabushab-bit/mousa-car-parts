/**
 * Fast offline phrase builder with fluent Arabic ordering
 */
function buildOfflineArabic(text) {
  let result = text;
  for (const item of termGlossary) {
    if (result.includes(item.cn)) {
      result = result.split(item.cn).join(` ${item.ar} `);
    }
  }

  // Strip any unmapped Chinese characters to ensure 100% clean Arabic output
  result = result.replace(/[\u4e00-\u9fa5]+/g, '');

  // Re-order 'تجميعة' (assembly) to the front if present
  if (result.includes('تجميعة') && !result.startsWith('تجميعة')) {
    result = 'تجميعة ' + result.replace(/تجميعة/g, '').trim();
  }

  // Normalize spaces and common duplicate Arabic phrases
  result = result
    .replace(/\s+/g, ' ')
    .replace(/الباب الأمامي الأيمن تنورة الباب/g, 'تنورة الباب الأمامي الأيمن')
    .replace(/الباب الأمامي الأيسر تنورة الباب/g, 'تنورة الباب الأمامي الأيسر')
    .replace(/الباب الخلفي الأيمن تنورة الباب/g, 'تنورة الباب الخلفي الأيمن')
    .replace(/الباب الخلفي الأيسر تنورة الباب/g, 'تنورة الباب الخلفي الأيسر')
    .replace(/الرفرف الرفرف/g, 'الرفرف')
    .replace(/الباب الباب/g, 'الباب')
    .replace(/المصد المصد/g, 'المصد')
    .trim();

  return result;
}

/**
 * Fast Async Translation with 800ms hard timeout protection
 */
export async function translateCnToAr(text) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  if (!trimmed) return '';

  // 1. Direct dictionary match (0ms)
  if (dictionary[trimmed]) {
    return dictionary[trimmed];
  }

  const hasChinese = /[\u4e00-\u9fa5]/.test(trimmed);
  if (!hasChinese) {
    return trimmed;
  }

  // 2. Generate instant offline human Arabic translation result
  const offlineResult = buildOfflineArabic(trimmed);

  if (offlineResult && offlineResult !== trimmed && /[\u0600-\u06FF]/.test(offlineResult)) {
    dictionary[trimmed] = offlineResult;
    return offlineResult;
  }

  // 3. Online fallback with strict 800ms AbortController timeout
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 800);

    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=zh-CN&tl=ar&dt=t&q=${encodeURIComponent(trimmed)}`;
    const response = await fetch(url, { signal: controller.signal });
    clearTimeout(timeoutId);

    if (response.ok) {
      const data = await response.json();
      if (data && data[0] && data[0][0] && data[0][0][0]) {
        let translated = data[0][0][0].trim();
        // Clean up online translation result to human terminology
        translated = translated
          .replace(/الوفد المرافق/g, 'تجميعة')
          .replace(/مجمع/g, 'تجميعة')
          .replace(/جناح/g, 'رفرف')
          .replace(/غطاء المحرك/g, 'كابوت (غطاء المحرك)');

        if (translated) {
          dictionary[trimmed] = translated;
          return translated;
        }
      }
    }
  } catch (err) {
    // Timeout or network error -> fallback immediately to offline result
  }

  dictionary[trimmed] = offlineResult || trimmed;
  return offlineResult || trimmed;
}

